def write_demo_books(directory: Path) -> None:
    datasets = [(name, demo_rows(month)) for month, name in [(1, "январь 2025"), (2, "февраль 2025")]]
    timestamp = xlwt.easyxf(num_format_str="YYYY-MM-DD HH:MM")
    for file, title in zip(Book, TITLES):
        workbook = xlwt.Workbook()
        for name, data in datasets:
            sheet = workbook.add_sheet(name)
            for column, heading in HEADINGS[file].items():
                sheet.write(0, column, heading)
            for index, values in enumerate(data[file], start=1):
                for column, value in values.items():
                    if isinstance(value, date):
                        sheet.write(index, column, value, timestamp)
                    else:
                        sheet.write(index, column, value)
        workbook.save(str(directory / f"{file.value}. {title}.xls"))
